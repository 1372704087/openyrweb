/**
 * ObjectType — 世界对象的类别标签（枚举，值连续无断档）。
 *
 * 由 engine/type/ObjectType.ts.js 重写为 TS（行为完全一致）。两个文件并存期间，
 * 本文件才是修改目标：tools/repack.mjs 打包时优先采用 .ts 模块的编译产物。
 *
 * 用途：GameObject 用 `type` 字段区分"这是个什么东西"，据此分发渲染、物理、
 * 选中与规则查询；game/gameobject/ObjectFactory 按它决定实例化哪个类，
 * data/mapObjects 与 game/art/ObjectArt 按它索引地图对象与美术定义。
 *
 * 数值稳定性：数值仅为内部序号，不参与网络/回放序列化（那两处各有自己的枚举）；
 * 但仍请勿重排或重编号 —— 需与 .ts.js 孪生逐值一致，tests/ts-parity.mjs 会校验
 * 代表值与键数量。
 */
export enum ObjectType {
  /** 未指定：哨兵值（代码中不按名引用），表示该处没有真实对象。 */
  None = 0,
  /** 飞行器：战机、直升机等空中单位。 */
  Aircraft = 1,
  /** 建筑：含防御工事与可占领的民用建筑。 */
  Building = 2,
  /** 步兵：单个步兵（含架起机枪等部署形态）。 */
  Infantry = 3,
  /** 地块覆盖物：矿石/宝石矿、围墙、桥面等贴在格子上的 overlay 层对象。 */
  Overlay = 4,
  /** 地面污渍：弹坑、履带痕、爆炸焦痕等装饰性贴花。 */
  Smudge = 5,
  /** 地形对象：树木、岩石、路标等场景物（通常不可选中，部分可被摧毁）。 */
  Terrain = 6,
  /** 载具：坦克、采矿车、舰船等地面/水面单位。 */
  Vehicle = 7,
  /** 动画对象：作为独立实体存在的动画（爆炸、烟雾等纯表现对象）。 */
  Animation = 8,
  /** 弹丸：飞行中的炮弹、导弹、抛射物。 */
  Projectile = 9,
  /** 体素动画：以 VXL 体素模型渲染的动画，如碎片飞散、残骸坠落。 */
  VoxelAnim = 10,
  /** 碎片：对象被摧毁后产生的可动残骸。 */
  Debris = 11,
}
