/**
 * DeathType — 单位/建筑的死亡表现分类。
 *
 * 决定摧毁动画与音效的播放方式（正常爆炸、被碾压、时间冻结消失、
 * 沉入水下等）。引擎侧按此值选择对应的死亡动画资源。
 *
 * 由 game/gameobject/common/DeathType.ts.js 重写为 TS（行为完全一致，
 * 枚举值经脚本提取核对）。两个文件并存期间，本文件才是修改目标：
 * tools/repack.mjs 打包时优先采用 .ts 模块的编译产物。
 */
export enum DeathType {
  /** 未死亡。 */
  None = 0,
  /** 常规被击毁（爆炸）。 */
  Normal = 1,
  /** 被炸药/自爆拆除（如 C4、自爆卡车）。 */
  Demolish = 2,
  /** 被碾压致死。 */
  Crush = 3,
  /** 被超时空传送/时间武器抹除（无爆炸，直接消失）。 */
  Temporal = 4,
  /** 沉入水中（船只在水面被击沉的表现）。 */
  Sink = 5,
}
